"""Render the Jinja2 script templates in pdxscript/templates.

Templates only lay text out. What goes into them (names, clone sources, nodes) is
decided by the generator; names come from core.naming.
"""
from __future__ import annotations

from functools import lru_cache
from typing import Any

from jinja2 import Environment, PackageLoader, StrictUndefined

HEADER = "# Generated by eu4unitgen. Regenerate rather than editing by hand."


class RenderError(ValueError):
    pass


def quote(value: Any) -> str:
    """A script string: "value". Script strings can't hold a quote or a line break."""
    text = str(value)
    if '"' in text or "\n" in text or "\r" in text:
        raise RenderError(f"script string can't contain a quote or line break: {text!r}")
    return f'"{text}"'


def loc_quote(value: Any) -> str:
    """A localisation value. UNVERIFIED how the loc reader treats an inner '"', so refuse it."""
    text = str(value)
    if '"' in text or "\n" in text or "\r" in text:
        raise RenderError(f"localisation text can't contain a quote or line break (yet): {text!r}")
    return f'"{text}"'


@lru_cache(maxsize=1)
def environment() -> Environment:
    env = Environment(
        loader=PackageLoader("eu4unitgen.pdxscript", "templates"),
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
        autoescape=False,
    )
    env.filters["q"] = quote
    env.filters["locq"] = loc_quote
    return env


def render(template: str, **context: Any) -> str:
    context.setdefault("header", HEADER)
    return environment().get_template(template).render(**context)
