"""Tests for export/writer.py: dry-run plan + diff, ownership, manifest, atomic apply."""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from eu4unitgen.cli import main as cli_main
from eu4unitgen.core.generator import generate
from eu4unitgen.core.naming import MANIFEST_FILE
from eu4unitgen.core.nation import Nation
from eu4unitgen.library.scanner import GameFiles
from eu4unitgen.export.writer import (
    BLOCKED, CREATE, UNCHANGED, UPDATE, ExportError, apply_export, plan_export, read_manifest, sha256,
)

MIL = "common/technologies/mil.txt"


@pytest.fixture
def gen(project, nation, game):
    files, idx = game
    return generate(project, nation, files, idx)


def _plan(mod_root, gen, game, errors=None):
    return plan_export(mod_root, gen, game[0], errors)


def _snapshot(root: Path) -> dict[str, bytes]:
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in root.rglob("*") if p.is_file()} if root.exists() else {}


def test_dry_run_writes_nothing(mod_root, gen, game):
    plan = _plan(mod_root, gen, game)
    assert not mod_root.exists()
    assert {f.action for f in plan.files} == {CREATE} and plan.can_apply
    assert len(plan.files) == len(gen.files)


def test_diff_shows_new_files_and_only_added_mil_lines(mod_root, gen, game):
    text = _plan(mod_root, gen, game).diff_text()
    assert "+++ b/gfx/entities/hr_mac_units.asset" in text and "--- /dev/null" in text
    assert "--- vanilla/common/technologies/mil.txt" in text
    mil_diff = text.split("--- vanilla/common/technologies/mil.txt", 1)[1].split("\n--- ", 1)[0]
    added = [ln for ln in mil_diff.splitlines() if ln.startswith("+") and not ln.startswith("+++")]
    removed = [ln for ln in mil_diff.splitlines() if ln.startswith("-") and not ln.startswith("---")]
    assert len(added) == 12 and removed == []
    assert "# CREATE    common/technologies/mil.txt (new in mod: vanilla copy + additions)" in text


def test_apply_writes_files_and_manifest(mod_root, gen, game):
    written = apply_export(_plan(mod_root, gen, game))
    assert len(written) == len(gen.files)
    for f in gen.files.values():
        assert (mod_root / f.path).read_bytes() == f.data
    manifest = read_manifest(mod_root)
    assert manifest["files"][MIL]["sha256"] == sha256(gen.files[MIL].data)
    assert manifest["files"][MIL]["sets"] == ["mac"] and manifest["updated"]
    assert not list(mod_root.rglob("*.tmp"))


def test_second_run_is_unchanged(mod_root, gen, game):
    apply_export(_plan(mod_root, gen, game))
    plan = _plan(mod_root, gen, game)
    assert {f.action for f in plan.files} == {UNCHANGED} and plan.diff_text().count("+++") == 0


def test_regenerated_file_is_an_update(mod_root, gen, game, project, nation):
    apply_export(_plan(mod_root, gen, game))
    project.entity_version = 21
    gen2 = generate(project, nation, *game)
    plan = _plan(mod_root, gen2, game)
    updates = {f.path for f in plan.by(UPDATE)}
    assert updates == {"gfx/entities/hr_mac_units.asset", "gfx/entities/hr_hellenicgfx_units.asset"}
    assert "-\tversion = 20" in plan.diff_text() and "+\tversion = 21" in plan.diff_text()


def test_hand_edited_file_is_blocked(mod_root, gen, game):
    apply_export(_plan(mod_root, gen, game))
    target = mod_root / "gfx/sprite_packs/hr_mac_pack.txt"
    target.write_bytes(target.read_bytes() + b"# my note\n")
    plan = _plan(mod_root, gen, game)
    (blocked,) = plan.by(BLOCKED)
    assert blocked.path == "gfx/sprite_packs/hr_mac_pack.txt" and "edited since" in blocked.reason
    assert not plan.can_apply
    before = _snapshot(mod_root)
    with pytest.raises(ExportError):
        apply_export(plan)
    assert _snapshot(mod_root) == before


def test_foreign_file_is_never_overwritten(mod_root, gen, game):
    (mod_root / "common/technologies").mkdir(parents=True)
    (mod_root / MIL).write_bytes(b"technology = { year = 1 }\n")
    plan = _plan(mod_root, gen, game)
    (blocked,) = plan.by(BLOCKED)
    assert blocked.path == MIL and "not generated by eu4unitgen" in blocked.reason and "INTEGRATION.md" in blocked.reason
    assert "--- a/common/technologies/mil.txt" in plan.diff_text()
    with pytest.raises(ExportError):
        apply_export(plan)
    assert (mod_root / MIL).read_bytes() == b"technology = { year = 1 }\n"


def test_validation_errors_block_export(mod_root, gen, game):
    plan = _plan(mod_root, gen, game, errors=["ERROR missing_nodes: x"])
    assert not plan.can_apply and "VALIDATION ERROR" in plan.diff_text()
    with pytest.raises(ExportError):
        apply_export(plan)
    assert not mod_root.exists()


def test_stale_files_reported_not_deleted(mod_root, gen, game):
    apply_export(_plan(mod_root, gen, game))
    del gen.files["common/units/hr_mac_artillery_4.txt"]
    plan = _plan(mod_root, gen, game)
    assert plan.stale == ["common/units/hr_mac_artillery_4.txt"]
    apply_export(plan)
    assert (mod_root / "common/units/hr_mac_artillery_4.txt").exists()
    assert "common/units/hr_mac_artillery_4.txt" in read_manifest(mod_root)["files"]


def test_two_nations_share_files_in_the_manifest(mod_root, gen, game, project):
    apply_export(_plan(mod_root, gen, game))
    epi = generate(project, Nation("EPI", "hellenicgfx"), *game, mod=GameFiles(mod_root, include_dlc=False))
    plan = _plan(mod_root, epi, game)
    assert plan.can_apply, plan.summary()
    apply_export(plan)
    files = read_manifest(mod_root)["files"]
    assert files["common/graphicalculturetype.txt"]["sets"] == ["epi", "mac"]
    assert files["gfx/entities/hr_mac_units.asset"]["sets"] == ["mac"]
    mil = (mod_root / MIL).read_text()
    assert "enable = hr_mac_infantry_1" in mil and "enable = hr_epi_infantry_1" in mil
    assert (mod_root / "common/graphicalculturetype.txt").read_text().count("hellenicgfx") == 1


def test_apply_refuses_if_folder_changed_after_planning(mod_root, gen, game):
    plan = _plan(mod_root, gen, game)
    (mod_root / "gfx/entities").mkdir(parents=True)
    (mod_root / "gfx/entities/hr_mac_units.asset").write_text("# someone else\n")
    with pytest.raises(ExportError, match="appeared after the dry run"):
        apply_export(plan)
    assert (mod_root / "gfx/entities/hr_mac_units.asset").read_text() == "# someone else\n"


def test_corrupt_manifest_stops_everything(mod_root, gen, game):
    (mod_root / ".eu4unitgen").mkdir(parents=True)
    (mod_root / MANIFEST_FILE).write_text("{not json")
    with pytest.raises(ExportError, match="unreadable"):
        _plan(mod_root, gen, game)


def test_manifest_is_valid_json_with_sorted_paths(mod_root, gen, game):
    apply_export(_plan(mod_root, gen, game))
    doc = json.loads((mod_root / MANIFEST_FILE).read_text(encoding="utf-8"))
    assert list(doc["files"]) == sorted(doc["files"]) and doc["tool"] == "eu4unitgen"


def test_cli_generate_writes_package_only(mod_root, fake_install, tmp_path, capsys):
    out = tmp_path / "output"
    code = cli_main(["generate", "--tag", "MAC", "--gfx", "hellenicgfx", "--eu4", str(fake_install),
                     "--out", str(out), "--mod", str(mod_root)])
    assert code == 0 and not mod_root.exists()
    pkg = out / "mac"
    files = sorted(p.relative_to(pkg).as_posix() for p in pkg.rglob("*") if p.is_file())
    assert "INTEGRATION.md" in files and "gfx/entities/hr_mac_units.asset" in files
    assert "common/technologies/mil.txt" not in files and "common/graphicalculturetype.txt" not in files
    assert not any(f.startswith(".eu4unitgen") for f in files)  # manifest lives beside the package
    assert (out / ".eu4unitgen" / "mac.manifest.json").is_file()
    assert "package: " in capsys.readouterr().out
    assert cli_main(["generate", "--tag", "MAC", "--gfx", "hellenicgfx", "--eu4", str(fake_install),
                     "--out", str(out)]) == 0  # second run: unchanged, no conflict


def test_cli_generate_dry_run_writes_nothing(fake_install, tmp_path, capsys):
    out = tmp_path / "output"
    assert cli_main(["generate", "--tag", "MAC", "--gfx", "hellenicgfx", "--eu4", str(fake_install),
                     "--out", str(out), "--dry-run"]) == 0
    assert not out.exists() and "+++ b/mac/INTEGRATION.md" in capsys.readouterr().out


@pytest.mark.parametrize("make_mod", ["descriptor", "sibling", "inside_mod_dir"])
def test_generate_refuses_mod_folders(make_mod, fake_install, tmp_path, monkeypatch, capsys):
    import eu4unitgen.cli as cli
    mod_dir = tmp_path / "Paradox" / "mod"
    target = mod_dir / "some_mod" / "out"
    target.mkdir(parents=True)
    if make_mod == "descriptor":
        (mod_dir / "some_mod" / "descriptor.mod").write_text('name="x"\n')
    elif make_mod == "sibling":
        (mod_dir / "some_mod.mod").write_text('name="x"\n')
    monkeypatch.setattr(cli, "default_mod_dir", lambda: mod_dir if make_mod == "inside_mod_dir" else tmp_path / "elsewhere")
    code = cli_main(["generate", "--tag", "MAC", "--gfx", "hellenicgfx", "--eu4", str(fake_install), "--out", str(target)])
    assert code == 1 and "REFUSED" in capsys.readouterr().out
    assert list(target.iterdir()) == []
